import pandas as pd
import matplotlib.pyplot as plt

# Read data from CSV file
df = pd.read_csv("sales_data.csv")

# Display the data
print(df)

# Create a line chart
plt.plot(
    df["Month"],
    df["Sales"],
    marker="o",
    label="Sales",
    color="blue",
)

plt.plot(
    df["Month"],
    df["Expenses"],
    marker="s",
    label="Expenses",
    color="red",
)

# Add chart information
plt.title("Monthly Sales and Expenses")
plt.xlabel("Month")
plt.ylabel("Amount ($)")
plt.legend()
plt.grid(True)

# Display chart
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

