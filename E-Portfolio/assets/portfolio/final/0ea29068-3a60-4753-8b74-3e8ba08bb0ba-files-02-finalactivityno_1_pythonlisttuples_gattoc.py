# Difficult Sample 10: Inventory Management

inventory = [
    ("Mouse", 10, 350),
    ("Keyboard", 5, 650),
    ("Monitor", 3, 5500),
    ("USB Drive", 20, 250),
    ("Headset", 4, 1200)
]

low_stock_limit = 5
total_inventory_value = 0
low_stock = []
stock_values = []

for name, quantity, price in inventory:
    value = quantity * price
    total_inventory_value += value

    stock_values.append((name, value))

    if quantity < low_stock_limit:
        low_stock.append((name, quantity))

stock_values.sort(key=lambda item: item[1], reverse=True)

print("INVENTORY REPORT")

for name, quantity, price in inventory:
    print(
        f"{name}: Quantity={quantity}, "
        f"Price={price}, Value={quantity * price}"
    )

print("\nTotal Inventory Value:", total_inventory_value)
print("Products Below Stock Limit:", low_stock)