# Difficult Sample 3: Frequency Distribution

responses = [
    "Python", "Java", "Python", "C++",
    "Java", "Python", "SQL", "C++",
    "Java", "SQL", "Python"
]

frequency = []

for language in responses:
    found = False

    for i in range(len(frequency)):
        if frequency[i][0] == language:
            frequency[i] = (
                language,
                frequency[i][1] + 1
            )
            found = True
            break

    if not found:
        frequency.append((language, 1))

print("Language Frequency")

for language, count in frequency:
    print(language, ":", count)

